/* The Turning Point Project – site logic. No dependencies; data comes from data/site.js
   (generated by scripts/build_site_data.py from the documents in docs/). */
(function () {
  "use strict";
  const D = window.SITE_DATA || {};
  const $ = (s, el = document) => el.querySelector(s);
  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const pill = (kind, text) => `<span class="pill ${kind}">${esc(text)}</span>`;
  const LABEL = { evidence: "Evidence", hypothesis: "Hypothesis", uncertain: "Uncertain", blocked: "Not testable here" };

  /* theme */
  const tb = $("#themeBtn");
  tb.addEventListener("click", () => {
    const cur = document.documentElement.dataset.theme ||
      (matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");
    const next = cur === "dark" ? "light" : "dark";
    document.documentElement.dataset.theme = next;
    try { localStorage.setItem("tpp-theme", next); } catch (e) { /* storage unavailable */ }
  });

  /* nav highlighting */
  const links = [...document.querySelectorAll("nav.main a")];
  const io = new IntersectionObserver((ents) => ents.forEach((e) => {
    if (e.isIntersecting) links.forEach((a) => a.setAttribute("aria-current", a.getAttribute("href") === "#" + e.target.id ? "true" : "false"));
  }), { rootMargin: "-45% 0px -50% 0px" });
  document.querySelectorAll("main section").forEach((s) => io.observe(s));

  /* overview */
  $("#conceptCards").innerHTML = (D.concepts || []).map((c) => `<div class="card"><div class="eyebrow">${esc(c.id)}</div>
    <h3>${esc(c.title)}</h3><p>${esc(c.question)}</p><p class="small"><strong>What can answer it:</strong> ${esc(c.evidence)}</p></div>`).join("");
  $("#statusGrid").innerHTML = (D.status || []).map((s) => `<div class="card ${esc(s.state)}"><h3>${esc(s.title)}</h3>
    <p class="small">${esc(s.text)}</p></div>`).join("");

  /* timeline + coverage */
  const stages = D.stages || [];
  const datasets = D.datasets || [];
  const AMIN = 0, AMAX = 45;
  const pct = (a) => ((Math.max(AMIN, Math.min(AMAX, a)) - AMIN) / (AMAX - AMIN)) * 100;
  function renderCoverage(stage) {
    const ticks = [0, 5, 10, 15, 20, 25, 30, 35, 40, 45];
    let html = "";
    datasets.forEach((d) => {
      const overl = !stage || (d.ages[1] >= stage.ages[0] && d.ages[0] <= stage.ages[1]);
      html += `<div class="cov-row"><div>${esc(d.short)}</div><div class="cov-track">
        <div class="cov-bar ${overl ? "" : "dim"}" style="left:${pct(d.ages[0])}%;width:${pct(d.ages[1]) - pct(d.ages[0])}%"
        title="${esc(d.short)}: about ages ${d.ages[0]}–${d.ages[1]}"></div>
        ${stage ? `<div class="cov-hl" style="left:${pct(stage.ages[0])}%;width:${pct(stage.ages[1] + 1) - pct(stage.ages[0])}%"></div>` : ""}
        </div></div>`;
    });
    html += `<div class="cov-axis"><div></div><div class="ticks">${ticks.map((t) => `<span style="left:${pct(t)}%">${t}</span>`).join("")}</div></div>`;
    $("#coverage").innerHTML = html;
    $("#coverageTable").innerHTML = `<thead><tr><th>Dataset</th><th>Approx. ages observed</th><th>Covers selected window?</th></tr></thead><tbody>` +
      datasets.map((d) => `<tr><td>${esc(d.name)}</td><td>${d.ages[0]}–${d.ages[1]}</td><td>${!stage || (d.ages[1] >= stage.ages[0] && d.ages[0] <= stage.ages[1]) ? "Yes" : "No"}</td></tr>`).join("") + "</tbody>";
  }
  function selectStage(i, focus) {
    const s = stages[i];
    [...$("#stageTabs").children].forEach((b, j) => { b.setAttribute("aria-selected", j === i); b.tabIndex = j === i ? 0 : -1; });
    if (focus) $("#stageTabs").children[i].focus();
    const list = (arr) => (arr || []).map((e) => `<li>${pill(e.label, LABEL[e.label])} ${esc(e.text)}${e.cite ? ` <span class="small">(${esc(e.cite)})</span>` : ""}</li>`).join("");
    const cover = datasets.filter((d) => d.ages[1] >= s.ages[0] && d.ages[0] <= s.ages[1]).map((d) => d.short);
    $("#stagePanel").innerHTML = `<h3 style="margin-top:0">${esc(s.name)} · ages ${s.ages[0]}–${s.ages[1]} ${pill("hypothesis", s.hid)}</h3>
      <p><strong>Hypothesis.</strong> ${esc(s.hypothesis)}</p>
      <div class="grid g2"><div><h4>What published research says</h4><ul>${list(s.evidence)}</ul></div>
      <div><h4>What remains open</h4><ul>${list(s.open)}</ul>
      <h4>Datasets observing these ages</h4><p>${cover.length ? cover.map((c) => `<span class="pill uncertain">${esc(c)}</span>`).join("") : "None among those audited."}</p>
      <p class="small">${esc(s.feasibility || "")}</p></div></div>`;
    $("#stagePanel").setAttribute("aria-labelledby", "stage-tab-" + i);
    renderCoverage(s);
  }
  $("#stageTabs").innerHTML = stages.map((s, i) => `<button class="stage" role="tab" id="stage-tab-${i}" aria-controls="stagePanel"
      aria-selected="false" tabindex="-1"><div class="ages">${s.ages[0]}–${s.ages[1]}</div><div class="nm">${esc(s.name)}</div></button>`).join("");
  [...$("#stageTabs").children].forEach((b, i) => {
    b.addEventListener("click", () => selectStage(i));
    b.addEventListener("keydown", (e) => {
      if (e.key === "ArrowRight" || e.key === "ArrowLeft") {
        e.preventDefault();
        selectStage((i + (e.key === "ArrowRight" ? 1 : stages.length - 1)) % stages.length, true);
      }
    });
  });
  if (stages.length) selectStage(1); else renderCoverage(null);

  /* framework diagram */
  const N = D.framework?.nodes || [];
  const E = D.framework?.edges || [];
  const svg = $("#fwSvg");
  const NS = "http://www.w3.org/2000/svg";
  const W = 150, H = 46;
  const byId = Object.fromEntries(N.map((n) => [n.id, n]));
  function edgePath(a, b) {
    const x1 = a.x + W / 2, y1 = a.y + H / 2, x2 = b.x + W / 2, y2 = b.y + H / 2;
    const dx = x2 - x1, dy = y2 - y1;
    const t = (w, h) => Math.min(Math.abs((w / 2) / (dx || 1e-9)), Math.abs((h / 2) / (dy || 1e-9)));
    const s1 = t(W + 6, H + 6), s2 = t(W + 14, H + 14);
    return `M${x1 + dx * s1},${y1 + dy * s1} L${x2 - dx * s2},${y2 - dy * s2}`;
  }
  svg.innerHTML = `<defs><marker id="arr" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">
    <path d="M0,0 L10,5 L0,10 z" fill="currentColor"/></marker></defs>`;
  const gEdges = document.createElementNS(NS, "g");
  svg.appendChild(gEdges);
  E.forEach((e, k) => {
    const p = document.createElementNS(NS, "path");
    p.setAttribute("d", edgePath(byId[e.from], byId[e.to]));
    p.setAttribute("class", "fw-edge" + (e.kind === "confound" ? " dashed" : ""));
    p.setAttribute("marker-end", "url(#arr)");
    p.style.color = "var(--muted)";
    p.dataset.k = k;
    gEdges.appendChild(p);
  });
  N.forEach((n) => {
    const g = document.createElementNS(NS, "g");
    g.setAttribute("class", "fw-node " + (n.role || ""));
    g.setAttribute("tabindex", "0");
    g.setAttribute("role", "button");
    g.setAttribute("aria-label", n.label + ": show details");
    g.setAttribute("transform", `translate(${n.x},${n.y})`);
    const lines = n.label.split("\n");
    g.innerHTML = `<rect width="${W}" height="${H}" rx="8"></rect>` + lines.map((l, i) =>
      `<text x="${W / 2}" y="${H / 2 + (i - (lines.length - 1) / 2) * 15 + 4}" text-anchor="middle">${esc(l)}</text>`).join("");
    g.addEventListener("click", () => showNode(n.id));
    g.addEventListener("keydown", (ev) => { if (ev.key === "Enter" || ev.key === " ") { ev.preventDefault(); showNode(n.id); } });
    svg.appendChild(g);
    n.el = g;
  });
  let mode = "causal", active = N.find((n) => n.role === "exposure")?.id;
  function paint() {
    gEdges.querySelectorAll("path").forEach((p) => {
      const e = E[p.dataset.k];
      const vis = mode === "all" || e.kind === mode;
      p.style.display = vis ? "" : "none";
      const hl = vis && active && (e.from === active || e.to === active);
      p.classList.toggle("hl", hl);
      p.style.color = hl ? "var(--orange-bright)" : "var(--muted)";
    });
    N.forEach((n) => n.el.classList.toggle("active", n.id === active));
  }
  function showNode(id) {
    active = id;
    const n = byId[id];
    const ins = E.filter((e) => e.to === id && (mode === "all" || e.kind === mode)).map((e) => byId[e.from].label.replace("\n", " "));
    const outs = E.filter((e) => e.from === id && (mode === "all" || e.kind === mode)).map((e) => byId[e.to].label.replace("\n", " "));
    $("#fwPanel").innerHTML = `<div class="eyebrow">${esc(n.domain || "")}</div><h3>${esc(n.label.replace("\n", " "))}</h3>
      <p><strong>Role in paper 1:</strong> ${esc(n.paperRole)}</p>
      <p>${esc(n.description)}</p>
      <p class="small"><strong>Example constructs:</strong> ${esc((n.constructs || []).join(", "))}</p>
      ${ins.length ? `<p class="small"><strong>Arrows in (${mode}):</strong> ${esc(ins.join("; "))}</p>` : ""}
      ${outs.length ? `<p class="small"><strong>Arrows out (${mode}):</strong> ${esc(outs.join("; "))}</p>` : ""}
      <p class="small"><strong>Candidate measures found in the audit:</strong> ${n.measuredIn && n.measuredIn.length ? n.measuredIn.map((m) => `<span class="pill uncertain">${esc(m)}</span>`).join("") : "none recorded yet"}</p>
      ${n.caution ? `<p class="small">${pill("uncertain", "Caution")} ${esc(n.caution)}</p>` : ""}`;
    paint();
  }
  document.querySelectorAll('input[name="pathMode"]').forEach((r) => r.addEventListener("change", () => { mode = r.value; showNode(active); }));
  if (active) showNode(active);

  /* datasets */
  const ages = [...new Set(stages.flatMap((s) => s.ages))].sort((a, b) => a - b);
  for (let a = 5; a <= 30; a += 1) $("#dsAge").insertAdjacentHTML("beforeend", `<option value="${a}">${a}</option>`);
  function renderDatasets() {
    const a = +$("#dsAge").value || null, acc = $("#dsAccess").value;
    const rows = datasets.filter((d) => (!a || (d.ages[0] <= a && a <= d.ages[1])) && (!acc || d.public));
    $("#datasetCards").innerHTML = rows.map((d) => `<article class="card"><div class="eyebrow">${esc(d.steward)}</div>
      <h3>${esc(d.name)}</h3>
      <p class="small">${esc(d.population)}</p>
      <p><strong>Ages:</strong> ~${d.ages[0]}–${d.ages[1]} · <strong>Baseline n:</strong> ${esc(d.n)} · <strong>Waves:</strong> ${esc(d.waves)}</p>
      <p><strong>Adult support measures:</strong> ${esc(d.support)}</p>
      <p><strong>Adult education outcome:</strong> ${esc(d.outcome)}</p>
      <p><strong>Access:</strong> ${esc(d.access)}</p>
      <details><summary>Limitations</summary><p>${esc(d.limitations)}</p></details>
      <p class="small">${pill(d.verified ? "evidence" : "uncertain", d.verified ? "Documentation checked" : "Partly unverified")}
        ${d.doc_url ? `<a href="${esc(d.doc_url)}">Documentation</a>` : ""}</p></article>`).join("") ||
      `<p>No audited dataset matches these filters.</p>`;
  }
  ["#dsAge", "#dsAccess"].forEach((s) => $(s).addEventListener("change", renderDatasets));
  renderDatasets();
  $("#dsRecommendation").innerHTML = D.recommendation || "";

  /* evidence */
  const ev = D.evidence || [];
  const types = [...new Set(ev.map((r) => r.study_type))].sort();
  types.forEach((t) => $("#evType").insertAdjacentHTML("beforeend", `<option>${esc(t)}</option>`));
  function renderEvidence() {
    const q = $("#evSearch").value.toLowerCase().trim(), t = $("#evType").value, tim = $("#evTiming").checked;
    const rows = ev.filter((r) => (!t || r.study_type === t) && (!tim || /^(yes|partial)/i.test(r.age_or_timing_relevant || "")) &&
      (!q || Object.values(r).join(" ").toLowerCase().includes(q)));
    $("#evCount").textContent = `${rows.length} of ${ev.length} works`;
    $("#evTable").innerHTML = `<thead><tr><th>Study</th><th>Type</th><th>Population / design</th><th>Key finding (abstract-level)</th><th>Timing?</th></tr></thead><tbody>` +
      rows.map((r) => `<tr><td><strong>${esc(r.authors_short)}</strong> (${esc(r.year)}). ${r.doi ? `<a href="https://doi.org/${esc(r.doi)}">${esc(r.title)}</a>` : esc(r.title)}. <em>${esc(r.journal)}</em></td>
        <td>${esc(r.study_type)}</td><td class="small">${esc(r.population)}${r.design_or_method ? "; " + esc(r.design_or_method) : ""}</td>
        <td>${esc(r.key_finding)}${r.limitations ? `<div class="small">Limitations: ${esc(r.limitations)}</div>` : ""}</td><td>${esc(r.age_or_timing_relevant)}</td></tr>`).join("") + "</tbody>";
  }
  ["#evSearch", "#evType", "#evTiming"].forEach((s) => $(s).addEventListener("input", renderEvidence));
  renderEvidence();

  /* simulator (illustrative, analytic – no random data) */
  const ids = ["simBeta", "simA12", "simA18", "simG", "simRel"];
  const outs = { simBeta: "oBeta", simA12: "oA12", simA18: "oA18", simG: "oG", simRel: "oRel" };
  function sim() {
    const v = Object.fromEntries(ids.map((i) => [i, +$("#" + i).value]));
    ids.forEach((i) => ($("#" + outs[i]).textContent = v[i].toFixed(2)));
    const agesS = [12, 13, 14, 15, 16, 17, 18];
    const naive = agesS.map((a) => {
      const al = v.simA12 + (v.simA18 - v.simA12) * (a - 12) / 6;
      return v.simRel * (v.simBeta + v.simG * al / (al * al + 1));
    });
    const s = $("#simSvg"), L = 50, R = 540, T = 20, B = 290;
    const ymax = Math.max(0.8, ...naive, v.simBeta) * 1.05;
    const X = (a) => L + (a - 12) / 6 * (R - L), Y = (y) => B - y / ymax * (B - T);
    let g = `<title id="simTitle">Illustrative: true versus observed association by age</title><desc id="simDesc">Constant true effect ${v.simBeta.toFixed(2)};
      naive association ranges from ${Math.min(...naive).toFixed(2)} to ${Math.max(...naive).toFixed(2)}.</desc>`;
    g += `<g class="axis"><line x1="${L}" y1="${B}" x2="${R}" y2="${B}"/><line x1="${L}" y1="${T}" x2="${L}" y2="${B}"/>`;
    agesS.forEach((a) => (g += `<text x="${X(a)}" y="${B + 16}" text-anchor="middle">${a}</text>`));
    for (let y = 0; y <= ymax; y += 0.2) g += `<text x="${L - 6}" y="${Y(y) + 4}" text-anchor="end">${y.toFixed(1)}</text><line x1="${L}" x2="${R}" y1="${Y(y)}" y2="${Y(y)}" opacity=".35"/>`;
    g += `<text x="${(L + R) / 2}" y="${B + 34}" text-anchor="middle">Age when support is measured</text></g>`;
    g += `<line x1="${X(12)}" x2="${X(18)}" y1="${Y(v.simBeta)}" y2="${Y(v.simBeta)}" stroke="var(--blue)" stroke-width="3"/>`;
    g += `<polyline fill="none" stroke="var(--orange-bright)" stroke-width="3" stroke-dasharray="7 4" points="${agesS.map((a, i) => X(a) + "," + Y(naive[i])).join(" ")}"/>`;
    g += `<text x="${R - 4}" y="${Y(v.simBeta) - 8}" text-anchor="end" fill="var(--blue)" font-weight="700" font-size="13">True effect</text>`;
    g += `<text x="${R - 4}" y="${Y(naive[6]) + (naive[6] > v.simBeta ? -8 : 18)}" text-anchor="end" fill="var(--orange)" font-weight="700" font-size="13">What a naive survey regression shows</text>`;
    g += `<text x="${L + 6}" y="${T + 10}" fill="var(--bad)" font-size="11" font-weight="700">ILLUSTRATIVE – NO DATA</text>`;
    s.innerHTML = g;
    $("#simText").textContent = `The true effect is ${v.simBeta.toFixed(2)} at every age, but the naive association runs from ${naive[0].toFixed(2)} at 12 to ${naive[6].toFixed(2)} at 18. ` +
      (Math.abs(naive[6] - naive[0]) > 0.05 ? "A survey would wrongly suggest that timing matters." : "Here selection barely changes with age, so the naive line is flat (though still biased).");
  }
  ids.forEach((i) => $("#" + i).addEventListener("input", sim));
  sim();

  /* methods, findings, publications */
  const cards = (arr, cls) => (arr || []).map((c) => `<div class="card ${esc(c.state || "")}"><h3>${esc(c.title)}</h3><p class="small">${esc(c.text)}</p>
    ${c.link ? `<a href="${esc(c.link)}">${esc(c.linkText || "Open")}</a>` : ""}${c.status ? `<p>${pill(c.statusKind || "uncertain", c.status)}</p>` : ""}</div>`).join("");
  $("#methodCards").innerHTML = cards(D.methods);
  $("#findingsSteps").innerHTML = cards(D.findingsSteps);
  $("#pubCards").innerHTML = cards(D.publications);
  if (D.build) $("#buildInfo").textContent = ` · data built ${D.build.date}`;
})();
